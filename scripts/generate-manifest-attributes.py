#!/usr/bin/env python3
"""Write the names behind the manifest's numbered attributes, from the Android SDK.

A compiled manifest keeps android:launchMode="singleTask" as the number 2, and the APK
Inspector shows the name again. The names are the <enum> and <flag> children of each <attr> in
the SDK platform's attrs_manifest.xml, plus windowSoftInputMode from attrs.xml, which the
manifest shares with themes.

Run it with `python3 -I scripts/generate-manifest-attributes.py [path to sdk/platforms/android-N]`
(the newest installed platform by default), then `./gradlew ktfmtFormat`.
"""

import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "core" / "src" / "main" / "kotlin" / "com" / "droidective" / "core" / "apps" / "ManifestAttributes.kt"
SHARED = {"windowSoftInputMode"}


def platform() -> pathlib.Path:
    if len(sys.argv) > 1:
        return pathlib.Path(sys.argv[1])
    platforms = pathlib.Path.home() / "Library" / "Android" / "sdk" / "platforms"
    found = sorted(platforms.glob("android-*"), key=lambda p: [int(x) for x in p.name[8:].split(".") if x.isdigit()])
    if not found:
        sys.exit(f"No SDK platform under {platforms}; pass one.")
    return found[-1]


def named(path: pathlib.Path, only: set[str] | None) -> dict[str, tuple[bool, list[tuple[str, int]]]]:
    out: dict[str, tuple[bool, list[tuple[str, int]]]] = {}
    for attr in ET.parse(path).getroot().iter("attr"):
        name = attr.get("name")
        if only is not None and name not in only:
            continue
        children = [c for c in attr if c.tag in ("enum", "flag")]
        if not children or name in out:
            continue
        values = [(c.get("name"), int(c.get("value"), 0) & 0xFFFFFFFF) for c in children]
        out[name] = (children[0].tag == "flag", values)
    return out


def kotlin(value: int) -> str:
    return f"0x{value:x}" if value < 0x80000000 else f"0x{value:x}.toInt()"


def main() -> None:
    base = platform()
    values = base / "data" / "res" / "values"
    attributes = named(values / "attrs_manifest.xml", None)
    attributes.update(named(values / "attrs.xml", SHARED))
    lines = [
        f"// Generated by scripts/generate-manifest-attributes.py from the Android SDK's {base.name}:",
        "// data/res/values/attrs_manifest.xml, and windowSoftInputMode from attrs.xml. Regenerate it",
        "// rather than editing it.",
        "package com.droidective.core.apps",
        "",
        "internal object ManifestAttributes {",
        "    /** Each android: attribute whose number stands for names; true when they are flags. */",
        "    val names: Map<String, Pair<Boolean, List<Pair<String, Int>>>> =",
        "        mapOf(",
    ]
    for name in sorted(attributes):
        flags, pairs = attributes[name]
        entries = ", ".join(f'"{n}" to {kotlin(v)}' for n, v in pairs)
        lines.append(f'            "{name}" to ({"true" if flags else "false"} to listOf({entries})),')
    lines += ["        )", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(attributes)} attributes from {base.name} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
